#!/usr/bin/env node
// Phase 4 end condition, Node.js half: fetch the FIC render from the
// Sidecar HTTP path and embed it into a host page the way docs/05 says a
// real backend would -- alongside markup loom did NOT generate (a "legacy"
// nav/footer), proving embedding, not just string output.
//
// Usage: node embed_host_page.js http://127.0.0.1:8790/render out.html

const url = process.argv[2] || "http://127.0.0.1:8790/render";
const outPath = process.argv[3] || "host_node.html";

const res = await fetch(url);
const fragment = await res.text();

const page = `<!doctype html>
<html lang="ko">
<head><meta charset="utf-8" /><title>loom-fic Phase 4 - Node.js host (Sidecar HTTP)</title></head>
<body>
  <nav>legacy host nav (not generated by loom)</nav>
  <main id="loom-mount">${fragment}</main>
  <footer>legacy host footer (not generated by loom)</footer>
</body>
</html>
`;

const fs = await import("node:fs/promises");
await fs.writeFile(outPath, page);
console.log(`wrote ${outPath} (fetched via Sidecar HTTP from ${url})`);
