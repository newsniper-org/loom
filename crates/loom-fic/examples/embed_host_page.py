#!/usr/bin/env python3
"""Phase 4 end condition, Python half: render via the native C ABI binding
(ctypes, see native_binding.py) and embed the result into a host page --
proving a *second* language, via a *different* embedding path (native, not
Sidecar HTTP) than embed_host_page.js uses, can host the same component.

Usage: python3 embed_host_page.py /path/to/libloom_fic.so out.html
"""

import sys

from native_binding import render

lib_path = sys.argv[1] if len(sys.argv) > 1 else "./libloom_fic.so"
out_path = sys.argv[2] if len(sys.argv) > 2 else "host_python.html"

fragment = render(lib_path)

page = f"""<!doctype html>
<html lang="ko">
<head><meta charset="utf-8" /><title>loom-fic Phase 4 - Python host (native C ABI binding)</title></head>
<body>
  <nav>legacy host nav (not generated by loom)</nav>
  <main id="loom-mount">{fragment}</main>
  <footer>legacy host footer (not generated by loom)</footer>
</body>
</html>
"""

with open(out_path, "w") as f:
    f.write(page)
print(f"wrote {out_path} (rendered via native ctypes binding of {lib_path})")
